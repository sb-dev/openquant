// Generates the TypeScript bindings and the behaviour bundle module of packages/agents (OQ-03 section 3, OQ-05 section 7).
//
// Under dist/generated, which is never committed:
//
// - bundle.json, types.ts, contracts.ts, validators-first.js and validators-first.d.ts: the role request and result
//   contracts with the shared schemas they reference, through the generator of @openquant/api-contracts. Only the
//   validator that stops at the first error is emitted: a role result is untrusted, up to 512 KiB, and one bounded
//   diagnostic is all the host needs.
// - bundle.ts: the behaviour bundle. It checks bundle.manifest.json against the files first: every listed file, its
//   SHA-256, the file set and the digest of each derived, self-contained result schema. Any difference fails the
//   build and names `pnpm --filter @openquant/agents run bundle:update`. It then inlines the procedures and the
//   result schemas and binds the SHA-256 of the manifest bytes as the bundle hash. Request assembly reads this
//   module and never the filesystem.

import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  contractsModule,
  generate as generateSharedContracts,
  typesModule,
  validatorDeclarations,
  validatorModule,
} from '../../api-contracts/ts/tools/generate.ts';
import {
  bundleRoleSchemas,
  derivedEntries,
  fail,
  fileDigest,
  MANIFEST_FILE,
  MANIFEST_FORMAT,
  type Manifest,
  PILOT_SKILLS,
  RESULT_CONTRACTS,
  readSchemas,
  selfContainedSchema,
  sha256,
  shippedPaths,
  withBranchValidators,
} from './bundle-lib.ts';

const BANNER = 'Generated by tools/generate.ts from packages/agents and packages/api-contracts/schemas. Do not edit.';
const UPDATE_HINT = 'run `pnpm --filter @openquant/agents run bundle:update` and review the manifest change';

function writeIfChanged(path: string, text: string): boolean {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return false;
  const temporary = `${path}.${process.pid}.tmp`;
  writeFileSync(temporary, text);
  renameSync(temporary, path);
  return true;
}

/** The manifest, checked against the files. Returns its exact bytes, whose SHA-256 is the bundle hash. */
export async function verifiedManifest(
  packageRoot: string,
  bundle: ReturnType<typeof bundleRoleSchemas>,
): Promise<{ manifest: Manifest; bytes: Uint8Array }> {
  const path = resolve(packageRoot, MANIFEST_FILE);
  if (!existsSync(path)) fail(`${MANIFEST_FILE} is missing; ${UPDATE_HINT}`);
  const bytes = readFileSync(path);
  const manifest = JSON.parse(bytes.toString('utf8')) as Manifest;
  if (manifest.format !== MANIFEST_FORMAT) fail(`${MANIFEST_FILE}: format must be ${MANIFEST_FORMAT}`);
  if (manifest.methods.length !== 0) fail(`${MANIFEST_FILE}: the baseline bundle adopts no method note`);
  if (JSON.stringify(manifest.skills) !== JSON.stringify(PILOT_SKILLS)) {
    fail(`${MANIFEST_FILE}: the skills must be exactly the two pilot role modules`);
  }
  const expected = shippedPaths(packageRoot, manifest.skills);
  const listed = manifest.files.map((file) => file.path);
  if (JSON.stringify(listed) !== JSON.stringify(expected)) {
    fail(`${MANIFEST_FILE}: the listed files differ from the shipped files [${expected.join(', ')}]; ${UPDATE_HINT}`);
  }
  for (const file of manifest.files) {
    const actual = fileDigest(packageRoot, file.path);
    if (actual !== file.sha256) fail(`${file.path} changed after ${MANIFEST_FILE} recorded it; ${UPDATE_HINT}`);
  }
  const derived = await derivedEntries(bundle);
  if (JSON.stringify(manifest.derived) !== JSON.stringify(derived)) {
    fail(
      `${MANIFEST_FILE}: a derived result schema changed (a schema in packages/api-contracts or packages/agents); ${UPDATE_HINT}`,
    );
  }
  return { manifest, bytes };
}

export function bundleModule(
  packageRoot: string,
  manifest: Manifest,
  bytes: Uint8Array,
  bundle: ReturnType<typeof bundleRoleSchemas>,
): string {
  const procedures = Object.fromEntries(
    manifest.skills.map((skill) => [skill.id, readFileSync(resolve(packageRoot, skill.procedure), 'utf8')]),
  );
  const schemas = Object.fromEntries(RESULT_CONTRACTS.map((name) => [name, selfContainedSchema(bundle, name)]));
  const literal = (value: unknown) => JSON.stringify(value, null, 2);
  return [
    `// ${BANNER}`,
    '',
    `export const BUNDLE_ID = ${JSON.stringify(manifest.id)};`,
    `export const BUNDLE_VERSION = ${manifest.version};`,
    '/** SHA-256 of the exact bytes of bundle.manifest.json: it binds every shipped file and derived schema. */',
    `export const BUNDLE_HASH = ${JSON.stringify(sha256(bytes))} as const;`,
    '/** The exact bytes of bundle.manifest.json. */',
    `export const MANIFEST_TEXT = ${JSON.stringify(Buffer.from(bytes).toString('utf8'))};`,
    '/** The method notes of the bundle: none. The baseline bundle adopts no method note. */',
    'export const SUPPLIED_METHODS: readonly never[] = [];',
    '/** The procedure text of each role module, as the manifest lists it. */',
    `export const PROCEDURES = ${literal(procedures)} as const;`,
    '/** The self-contained result schema of each role contract: what the executor output must satisfy. */',
    `export const RESULT_SCHEMAS = ${literal(schemas)} as const;`,
    `export const FILES: readonly { readonly path: string; readonly sha256: string }[] = ${literal(manifest.files)};`,
    `export const DERIVED: readonly { readonly name: string; readonly sha256: string }[] = ${literal(manifest.derived)};`,
    '',
  ].join('\n');
}

export async function generate(packageRoot: string, outDir: string): Promise<string> {
  // The shared package generates its own files; the role modules import its source.
  const shared = resolve(packageRoot, '../api-contracts');
  if (!existsSync(resolve(shared, 'ts/dist/generated/contracts.ts'))) {
    await generateSharedContracts(resolve(shared, 'schemas'), resolve(shared, 'ts/dist/generated'));
  }
  const bundle = bundleRoleSchemas(readSchemas(packageRoot));
  const { manifest, bytes } = await verifiedManifest(packageRoot, bundle);
  const outputs: [string, string][] = [
    ['bundle.json', `${JSON.stringify(bundle.document, null, 2)}\n`],
    ['contracts.ts', contractsModule(bundle)],
    ['types.ts', await typesModule(bundle)],
    ['validators-first.js', validatorModule(withBranchValidators(bundle), false)],
    ['validators-first.d.ts', validatorDeclarations(withBranchValidators(bundle))],
    ['bundle.ts', bundleModule(packageRoot, manifest, bytes, bundle)],
  ];
  mkdirSync(outDir, { recursive: true });
  const changed = outputs.filter(([name, text]) => writeIfChanged(resolve(outDir, name), text)).map(([name]) => name);
  const definitions = Object.keys(bundle.document.$defs ?? {}).length;
  return `Generated ${bundle.contracts.length} role contracts and ${definitions} definitions; bundle ${sha256(bytes)}; ${changed.length ? `updated ${changed.join(', ')}` : 'no file changed'}.`;
}

if (import.meta.main) {
  const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  console.log(await generate(packageRoot, resolve(packageRoot, 'dist/generated')));
}
