// Generates the TypeScript bindings of the shared schemas (OQ-05 §7, OQ-06 §1).
//
// Every schema in packages/api-contracts/schemas is bundled into one document. Each `urn:` reference
// becomes a local `#/$defs/` reference, as build.rs does for the Rust bindings, so definition names
// must stay unique across all schemas. From the bundle this script writes, under dist/generated:
//
// - bundle.json: the bundled schema;
// - types.ts: TypeScript types (json-schema-to-typescript);
// - contracts.ts: the contract table, the type map and the decimal grammar constants;
// - validators-first.js and validators-all.js: Ajv standalone ESM validators that stop at the first
//   error or report all errors, with their .d.ts files.
//
// Nothing generated is committed. Writes are atomic and skip unchanged files, so parallel runs are safe.

import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneModule from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';

type Json = null | boolean | number | string | Json[] | JsonObject;
interface JsonObject {
  [key: string]: Json;
}

export interface SchemaSource {
  readonly file: string;
  readonly schema: Json;
}

export interface Contract {
  readonly name: string;
  readonly schemaId: string;
  readonly versionTag: string;
  readonly typeName: string;
}

export interface Bundle {
  readonly document: JsonObject;
  readonly contracts: readonly Contract[];
  readonly decimalPattern: string;
  readonly exactPattern: string;
  readonly exactMaxLength: number;
}

export const BUNDLE_ID = 'urn:openquant:bundle:1';
const SCHEMA_ID = /^urn:openquant:schema:([a-z][a-z0-9-]*):([1-9][0-9]*)$/;
const DEF_REF = /^#\/\$defs\/([A-Za-z][A-Za-z0-9]*)$/;
const TYPE_NAME = /^[A-Z][A-Za-z0-9]*$/;
const NON_VALIDATING = new Set(['$schema', '$id', '$defs', 'title', 'description']);
const BANNER = 'Generated by tools/generate.ts from packages/api-contracts/schemas. Do not edit.';

function fail(message: string): never {
  throw new Error(`schema bundle: ${message}`);
}

function isObject(value: Json | undefined): value is JsonObject {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

interface Parsed {
  readonly file: string;
  readonly name: string;
  readonly id: string;
  readonly title: string;
  readonly schema: JsonObject;
  readonly defs: JsonObject;
  readonly isRoot: boolean;
}

function parseSource({ file, schema }: SchemaSource): Parsed {
  if (!isObject(schema)) fail(`${file}: the root is not an object`);
  const id = schema.$id;
  const match = typeof id === 'string' ? SCHEMA_ID.exec(id) : null;
  if (typeof id !== 'string' || !match) fail(`${file}: $id must be urn:openquant:schema:<name>:<version>`);
  const name = match[1] ?? '';
  if (file !== `${name}.schema.json`) fail(`${file}: the file name does not match $id ${id}`);
  const title = schema.title;
  if (typeof title !== 'string' || !TYPE_NAME.test(title)) fail(`${file}: the title must be a type name`);
  const defs = schema.$defs ?? {};
  if (!isObject(defs)) fail(`${file}: $defs must be an object`);
  const isRoot = Object.keys(schema).some((key) => !NON_VALIDATING.has(key));
  return { file, name, id, title, schema, defs, isRoot };
}

function rewriteRef(ref: string, owner: Parsed, documents: ReadonlyMap<string, Parsed>): string {
  const hash = ref.indexOf('#');
  const base = hash < 0 ? ref : ref.slice(0, hash);
  const fragment = hash < 0 ? '' : ref.slice(hash);
  const target = base === '' ? owner : documents.get(base);
  if (!target) fail(`${owner.file}: unknown schema in reference ${ref}`);
  if (fragment === '') {
    if (!target.isRoot) fail(`${owner.file}: ${ref} names a schema that has no root`);
    return `#/$defs/${target.title}`;
  }
  const match = DEF_REF.exec(fragment);
  const name = match?.[1];
  if (name === undefined) fail(`${owner.file}: unsupported reference ${ref}`);
  if (!Object.hasOwn(target.defs, name)) fail(`${owner.file}: ${ref} is not defined in ${target.file}`);
  return `#/$defs/${name}`;
}

function rewrite(value: Json, owner: Parsed, documents: ReadonlyMap<string, Parsed>): Json {
  if (Array.isArray(value)) return value.map((item) => rewrite(item, owner, documents));
  if (!isObject(value)) return value;
  const out: JsonObject = {};
  for (const [key, child] of Object.entries(value)) {
    if (key === '$ref') {
      if (typeof child !== 'string') fail(`${owner.file}: $ref must be a string`);
      out[key] = rewriteRef(child, owner, documents);
    } else {
      out[key] = rewrite(child, owner, documents);
    }
  }
  return out;
}

function enumOf(schema: Json | undefined): string | undefined {
  if (!isObject(schema) || !isObject(schema.properties)) return undefined;
  const version = schema.properties.schema_version;
  if (!isObject(version) || !Array.isArray(version.enum) || version.enum.length !== 1) return undefined;
  const [tag] = version.enum;
  return typeof tag === 'string' ? tag : undefined;
}

// The schema_version tag of every form of a root: the root itself, or each oneOf branch.
function versionTags(source: Parsed): (string | undefined)[] {
  const branches = source.schema.oneOf;
  if (!Array.isArray(branches)) return [enumOf(source.schema)];
  return branches.map((branch) => {
    const ref = isObject(branch) ? branch.$ref : undefined;
    const name = typeof ref === 'string' ? DEF_REF.exec(ref)?.[1] : undefined;
    return name === undefined ? undefined : enumOf(source.defs[name]);
  });
}

function stringField(defs: ReadonlyMap<string, Json>, name: string, field: string): string {
  const def = defs.get(name);
  const value = isObject(def) ? def[field] : undefined;
  if (typeof value !== 'string') fail(`definition ${name} needs a string ${field}`);
  return value;
}

/** Bundle the schemas into one document with local references only. */
export function bundleSchemas(sources: readonly SchemaSource[]): Bundle {
  const parsed = [...sources].sort((a, b) => (a.file < b.file ? -1 : 1)).map(parseSource);
  const documents = new Map(parsed.map((source) => [source.id, source]));
  if (documents.size !== parsed.length) fail('two schemas share an $id');
  const defs = new Map<string, Json>();
  const add = (name: string, schema: Json, file: string) => {
    if (defs.has(name)) fail(`definition name collision: ${name} (${file})`);
    defs.set(name, schema);
  };
  const contracts: Contract[] = [];
  for (const source of parsed) {
    for (const [name, def] of Object.entries(source.defs)) add(name, rewrite(def, source, documents), source.file);
    if (!source.isRoot) continue;
    const { $schema: _schema, $id: _id, $defs: _defs, ...root } = source.schema;
    add(source.title, rewrite(root, source, documents), source.file);
    const versionTag = `${source.name}/${source.id.slice(source.id.lastIndexOf(':') + 1)}`;
    const tags = versionTags(source);
    if (tags.some((tag) => tag !== versionTag)) {
      fail(`${source.file}: every form must fix schema_version to ${JSON.stringify(versionTag)}`);
    }
    contracts.push({ name: source.name, schemaId: source.id, versionTag, typeName: source.title });
  }
  if (contracts.length === 0) fail('no contract roots found');
  const exactMaxLength = defs.get('Exact');
  const maxLength = isObject(exactMaxLength) ? exactMaxLength.maxLength : undefined;
  if (typeof maxLength !== 'number') fail('definition Exact needs maxLength');
  return {
    document: {
      $schema: 'https://json-schema.org/draft/2020-12/schema',
      $id: BUNDLE_ID,
      title: 'OpenQuantContracts',
      $defs: Object.fromEntries(defs),
    },
    contracts,
    decimalPattern: stringField(defs, 'Decimal', 'pattern'),
    exactPattern: stringField(defs, 'Exact', 'pattern'),
    exactMaxLength: maxLength,
  };
}

const standaloneCode = standaloneModule.default;
const CODE_POINT_LENGTH = /require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g;
const SCHEMA_MAPS = new Set(['properties', '$defs']);
const SCHEMA_VALUED = new Set(['items', 'additionalProperties']);

// The schema without title and description. Ajv embeds each schema as a constant, and these
// annotations are most of the text. They never affect validation.
function withoutAnnotations(schema: Json): Json {
  if (!isObject(schema)) return schema;
  const out: JsonObject = {};
  for (const [key, value] of Object.entries(schema)) {
    if (key === 'title' || key === 'description') continue;
    if (SCHEMA_MAPS.has(key) && isObject(value)) {
      out[key] = Object.fromEntries(Object.entries(value).map(([name, child]) => [name, withoutAnnotations(child)]));
    } else if (SCHEMA_VALUED.has(key)) {
      out[key] = withoutAnnotations(value);
    } else if (key === 'oneOf' && Array.isArray(value)) {
      out[key] = value.map(withoutAnnotations);
    } else {
      out[key] = value;
    }
  }
  return out;
}

/** Ajv standalone ESM validators for every contract root, free of require() and run-time code generation. */
export function validatorModule(bundle: Bundle, allErrors: boolean): string {
  const ajv = new Ajv2020({
    code: { source: true, esm: true },
    strict: true,
    allErrors,
    unicodeRegExp: true,
    inlineRefs: false,
  });
  ajv.addSchema(withoutAnnotations(bundle.document) as JsonObject);
  const exports = Object.fromEntries(bundle.contracts.map((c) => [c.typeName, `${BUNDLE_ID}#/$defs/${c.typeName}`]));
  let code = standaloneCode(ajv, exports).replace(/^"use strict";/, '');
  // maxLength counts code points. Ajv emits a require() of its runtime helper; inline an equivalent.
  code = code.replace(CODE_POINT_LENGTH, 'codePointLength');
  if (/\brequire\s*\(/.test(code)) fail('a generated validator still requires a CommonJS module');
  if (/\bnew Function\b|\beval\s*\(/.test(code)) fail('a generated validator compiles code at run time');
  const table = bundle.contracts.map((c) => `  ${JSON.stringify(c.name)}: ${c.typeName},`).join('\n');
  return [
    `// ${BANNER}`,
    `// allErrors: ${allErrors}`,
    'const codePointLength = (text) => {',
    '  let count = 0;',
    '  for (const _ of text) count += 1;',
    '  return count;',
    '};',
    code,
    `export const byContract = {\n${table}\n};`,
    '',
  ].join('\n');
}

export function validatorDeclarations(bundle: Bundle): string {
  return [
    `// ${BANNER}`,
    "import type { ContractName } from './contracts.ts';",
    '',
    'export interface ValidatorError {',
    '  readonly instancePath: string;',
    '  readonly schemaPath: string;',
    '  readonly keyword: string;',
    '  readonly params: Readonly<Record<string, unknown>>;',
    '  readonly message?: string;',
    '}',
    '',
    'export interface StandaloneValidator {',
    '  (data: unknown): boolean;',
    '  errors?: ValidatorError[] | null;',
    '}',
    '',
    ...bundle.contracts.map((c) => `export declare const ${c.typeName}: StandaloneValidator;`),
    'export declare const byContract: Readonly<Record<ContractName, StandaloneValidator>>;',
    '',
  ].join('\n');
}

export function contractsModule(bundle: Bundle): string {
  const rows = bundle.contracts.map(
    (c) =>
      `  ${JSON.stringify(c.name)}: { schemaId: ${JSON.stringify(c.schemaId)}, versionTag: ${JSON.stringify(c.versionTag)}, typeName: ${JSON.stringify(c.typeName)} },`,
  );
  const types = bundle.contracts.map((c) => `  ${JSON.stringify(c.name)}: Types.${c.typeName};`);
  return [
    `// ${BANNER}`,
    "import type * as Types from './types.ts';",
    '',
    `export const contracts = {\n${rows.join('\n')}\n} as const;`,
    '',
    'export type ContractName = keyof typeof contracts;',
    '',
    `export interface ContractTypes {\n${types.join('\n')}\n}`,
    '',
    '/** The decimal grammar of common.schema.json. A pattern failure with it is INVALID_DECIMAL. */',
    `export const DECIMAL_PATTERN = ${JSON.stringify(bundle.decimalPattern)};`,
    '/** The Exact grammar of common.schema.json: a decimal or a fraction n/d. */',
    `export const EXACT_PATTERN = ${JSON.stringify(bundle.exactPattern)};`,
    '/** The longest Exact text (maxLength of Exact). */',
    `export const EXACT_MAX_LENGTH = ${bundle.exactMaxLength};`,
    '',
  ].join('\n');
}

/** TypeScript types. Exact is an opaque branded string: TypeScript never computes with it. */
export async function typesModule(bundle: Bundle): Promise<string> {
  const input = structuredClone(bundle.document);
  const defs = input.$defs;
  if (!isObject(defs) || !isObject(defs.Exact)) fail('the bundle has no Exact definition');
  defs.Exact.tsType = "string & { readonly __brand: 'Exact' }";
  input.type = 'object';
  input.additionalProperties = false;
  input.properties = Object.fromEntries(bundle.contracts.map((c) => [c.typeName, { $ref: `#/$defs/${c.typeName}` }]));
  const text = await compile(input, 'OpenQuantContracts', {
    bannerComment: `/* ${BANNER} */`,
    additionalProperties: false,
    unreachableDefinitions: true,
    ignoreMinAndMaxItems: true,
    strictIndexSignatures: true,
    format: true,
  });
  for (const c of bundle.contracts) {
    if (!new RegExp(`^export (?:interface|type) ${c.typeName}\\b`, 'm').test(text))
      fail(`no type emitted for ${c.typeName}`);
  }
  if (!/^export type Exact = string & \{\s*readonly __brand: ["']Exact["']\s*\};$/m.test(text))
    fail('Exact is not branded');
  return text;
}

function writeIfChanged(path: string, text: string): boolean {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return false;
  const temporary = `${path}.${process.pid}.tmp`;
  writeFileSync(temporary, text);
  renameSync(temporary, path);
  return true;
}

export async function generate(schemaDir: string, outDir: string): Promise<string> {
  const files = readdirSync(schemaDir).filter((file) => file.endsWith('.schema.json'));
  const bundle = bundleSchemas(
    files.map((file) => ({ file, schema: JSON.parse(readFileSync(resolve(schemaDir, file), 'utf8')) as Json })),
  );
  const outputs: [string, string][] = [
    ['bundle.json', `${JSON.stringify(bundle.document, null, 2)}\n`],
    ['contracts.ts', contractsModule(bundle)],
    ['types.ts', await typesModule(bundle)],
    ['validators-first.js', validatorModule(bundle, false)],
    ['validators-first.d.ts', validatorDeclarations(bundle)],
    ['validators-all.js', validatorModule(bundle, true)],
    ['validators-all.d.ts', validatorDeclarations(bundle)],
  ];
  mkdirSync(outDir, { recursive: true });
  const changed = outputs.filter(([name, text]) => writeIfChanged(resolve(outDir, name), text)).map(([name]) => name);
  const definitions = Object.keys(bundle.document.$defs ?? {}).length;
  return `Generated ${bundle.contracts.length} contracts and ${definitions} definitions from ${files.length} schemas; ${changed.length ? `updated ${changed.join(', ')}` : 'no file changed'}.`;
}

