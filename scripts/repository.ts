export function read(base: string, path: string): string {
  return readFileSync(resolve(base, path), 'utf8');
}

export function paths(base: string): string[] {
  if (existsSync(resolve(base, '.git'))) {
    const result = spawnSync('git', ['ls-files', '-z'], { cwd: base, encoding: 'utf8' });
    if (result.status !== 0) throw new Error(`Cannot read Git index: ${result.stderr}`);
    return result.stdout.split('\0').filter(Boolean).sort();
  }
  const result: string[] = [];
  function walk(directory: string) {
    for (const item of readdirSync(resolve(base, directory), { withFileTypes: true })) {
      if (isIgnored(item.name)) continue;
      const path = directory ? `${directory}/${item.name}` : item.name;
      if (item.isSymbolicLink()) result.push(path);
      else if (item.isDirectory()) walk(path);
      else if (item.isFile()) result.push(path);
    }
  }
  walk('');
  return result.sort();
}

export function metadata(text: string): Record<string, string> {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!match) throw new Error('Missing front matter');
  const result: Record<string, string> = {};
  for (const line of match[1].split('\n')) {
    const field = /^([a-z]+): (.+)$/.exec(line);
    if (!field || result[field[1]]) throw new Error(`Invalid or duplicate metadata: ${line}`);
    result[field[1]] = field[2];
  }
  for (const key of ['id', 'title', 'version', 'status', 'updated', 'owns']) {
    if (!result[key]) throw new Error(`Missing metadata: ${key}`);
  }
  if (!/^OQ-0[1-7]$/.test(result.id)) throw new Error('Invalid spec ID');
  if (!/^\d+\.\d+\.\d+$/.test(result.version)) throw new Error('Invalid spec version');
  if (result.status !== 'canonical') throw new Error('Invalid spec status');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(result.updated)) throw new Error('Invalid spec date');
  return result;
}

export function specIndex(base: string): string {
  const rows = expectedSpecs.map((file) => {
    const m = metadata(read(base, `docs/specs/${file}`));
    if (m.id !== `OQ-${file.slice(0, 2)}`) throw new Error(`ID does not match filename: ${file}`);
    return `| [${m.id} — ${m.title.replace('OpenQuant — ', '')}](${file}) | ${m.version} | ${m.status} | ${m.owns} |`;
  });
  return `# Canonical specifications

<!-- Generated by scripts/generate-spec-index.ts. Edit document metadata, then regenerate. -->

These seven documents define the target product. The repository is a specification-first bootstrap. Application checkpoints are not implemented.

| Specification | Version | Status | Owns |
| --- | --- | --- | --- |
${rows.join('\n')}

## Authority

Each subject has one owner. Product design owns goals and scope. Trading domain owns financial meaning and safety invariants. Model execution owns delegated AI behaviour. UX owns interaction. Architecture owns technology and data boundaries. Engineering owns verification and delivery. Organisation owns public surfaces.

Cross-cutting changes update every affected owner in one reviewed change. Do not resolve a conflict through implementation alone. Research logs, examples, README text, and imported references cannot override these documents.

The agreed baseline is Design v2 plus Repository Design v1.1, including the Fly.io correction. The [migration record](../research-logs/2026-10-19-bootstrap-migration.md) records the consolidation. Original source bytes and hashes remain in the [reference archive](../research-logs/imported/README.md).

A01–A18 remain in the [trading domain](02-trading-domain-and-evaluation-spec.md#9-acceptance-and-preservation-of-results). R01–R10 remain in [engineering](06-engineering-delivery-and-operations-spec.md#8-delivery-checkpoints-and-acceptance). These are requirements, not test results.

## Changes

Update the owning document and its single metadata block. Regenerate this index with \`pnpm generate:spec-index\`. Run \`pnpm verify\`. A passing bootstrap check confirms repository integrity only; it does not accept M1–M4 or the public CLI release.
`;
}

export function repositoryTree(files: string[]): string {
  return '# OpenQuant repository files\n# Generated by scripts/generate-repository-tree.ts.\n# Git checkout: tracked index. Extracted archive: source files and symlink entries.\n\n' + files.join('\n') + '\n';
}

function isWithin(base: string, path: string): boolean {
  const rel = relative(base,path);
  return rel !== '..' && !rel.startsWith(`..${sep}`) && !isAbsolute(rel);
}

function repositoryPathError(base: string, file: string, files: Set<string>): string | undefined {
  const absolute = resolve(base,file);
  if (!isWithin(resolve(base),absolute)) return `Path escapes repository: ${file}`;
  // Check ancestors before resolving or reading a file. Git can still list children
  // after a tracked directory is replaced with a symlink in the working tree.
  for (let directory = dirname(absolute); directory !== resolve(base); directory = dirname(directory)) {
    try {
      if (lstatSync(directory).isSymbolicLink()) return `Symlink ancestor not allowed: ${file}`;
    } catch { return `Tracked file missing on disk: ${file}`; }
  }
  let stat;
  try { stat = lstatSync(absolute); }
  catch { return `Tracked file missing on disk: ${file}`; }
  if (!stat.isSymbolicLink()) return stat.isFile() ? undefined : `Not a regular source file: ${file}`;
  const match = /^\.claude\/skills\/([a-z0-9]+(?:-[a-z0-9]+)*)$/.exec(file);
  if (!match || readlinkSync(absolute) !== `../../.agents/skills/${match[1]}`) return `Symlink not allowed: ${file}`;
  const canonical = `.agents/skills/${match[1]}/SKILL.md`;
  const target = resolve(base,'.agents/skills',match[1]);
  try {
    if (!isWithin(realpathSync(base),realpathSync(target))) return `Skill symlink escapes repository: ${file}`;
    if (!lstatSync(target).isDirectory() || !files.has(canonical) || repositoryPathError(base,canonical,files)) {
      return `Skill symlink requires a regular tracked canonical SKILL.md: ${file}`;
    }
  } catch { return `Dangling skill symlink: ${file}`; }
  return undefined;
}

function stripFences(text: string): string {
  return text.replace(/^(`{3,}|~{3,})[^\n]*\n[\s\S]*?^\1[^\n]*(?:\n|$)/gm, '');
}

function anchors(text: string): Set<string> {
  const result = new Set<string>();
  for (const match of stripFences(text).matchAll(/^#{1,6}\s+(.+)$/gm)) {
    const slug = match[1].toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s/g, '-');
    let key = slug;
    let index = 1;
    while (result.has(key)) key = `${slug}-${index++}`;
    result.add(key);
  }
  return result;
}

export function localLinkErrors(base: string, file: string, text: string, files: Set<string>): string[] {
  const errors: string[] = [];
  for (const link of stripFences(text).matchAll(/\[[^\]\n]*\]\(([^\s)]+)\)/g)) {
    const target = link[1];
    if (/^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
    const [rawPath, rawAnchor] = target.split('#');
    let resolved: string;
    try { resolved = rawPath ? resolve(base, dirname(file), decodeURIComponent(rawPath)) : resolve(base, file); }
    catch { errors.push(`${file}: malformed link ${target}`); continue; }
    const rel = relative(base, resolved).replaceAll('\\', '/');
    if (rel.startsWith('../') || isAbsolute(rel)) { errors.push(`${file}: link escapes repository: ${target}`); continue; }
    if (!existsSync(resolved)) { errors.push(`${file}: missing local link ${target}`); continue; }
    if (!isWithin(realpathSync(base),realpathSync(resolved))) { errors.push(`${file}: link escapes repository: ${target}`); continue; }
    if (lstatSync(resolved).isDirectory()) {
      if (!files.has(`${rel}/README.md`)) errors.push(`${file}: directory link has no tracked README: ${target}`);
    } else if (!files.has(rel)) errors.push(`${file}: link points to an untracked file: ${target}`);
    if (rawAnchor && resolved.endsWith('.md')) {
      if (!anchors(readFileSync(resolved, 'utf8')).has(decodeURIComponent(rawAnchor))) errors.push(`${file}: missing anchor ${target}`);
    }
  }
  return errors;
}

// High-confidence credential patterns. Each needs the full token shape, or a value assigned to a name that
// says it holds a key, so text can still name a variable, a prefix or a placeholder. `firstParty` patterns
// skip vendored skills and imported references, whose examples are bound by recorded hashes.
export const credentialPatterns: ReadonlyArray<{ label: string; pattern: RegExp; firstParty?: true }> = [
  { label: 'GitHub token', pattern: /\b(?:ghp_[A-Za-z0-9]{36}|github_pat_[A-Za-z0-9_]{50,})\b/ },
  { label: 'AWS access key ID', pattern: /\bAKIA[A-Z0-9]{16}\b/ },
  { label: 'private key', pattern: /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/ },
  { label: 'Anthropic key', pattern: /\bsk-ant-[a-z]+\d{2}-[A-Za-z0-9_-]{40,}/ },
  { label: 'Fly.io token', pattern: /\bfo1_[A-Za-z0-9_-]{30,}|\bFlyV1\s+fm2_[A-Za-z0-9+/=_-]{40,}/ },
  { label: 'Alpaca key ID', pattern: /\b(?:APCA[_-]API[_-]KEY[_-]ID|ALPACA[_-](?:API[_-])?KEY(?:[_-]ID)?)["']?\s*[:=]\s*["']?(?:PK|AK)[A-Z0-9]{16,}\b/ },
  { label: 'Alpaca secret key', pattern: /\b(?:APCA[_-]API[_-]SECRET[_-]KEY|ALPACA[_-](?:API[_-])?SECRET(?:[_-]KEY)?)["']?\s*[:=]\s*["']?[A-Za-z0-9/+]{30,}/ },
  { label: 'Cloudflare token', pattern: /\b(?:CLOUDFLARE|CF)_API_(?:TOKEN|KEY)["']?\s*[:=]\s*["']?[A-Za-z0-9_-]{37,}/ },
  { label: 'Postgres URL with a password', pattern: /\bpostgres(?:ql)?:\/\/[^\s:@/'"`]+:(?![$<{])[^\s@/'"`]+@/, firstParty: true },
];

export function credentialErrors(file: string, text: string): string[] {
  const vendored = file.startsWith('.agents/skills/') || file.startsWith('docs/research-logs/imported/');
  return credentialPatterns.filter(({ pattern, firstParty }) => !(firstParty && vendored) && pattern.test(text)).map(({ label }) => `Potential credential in ${file}: ${label}`);
}

// The aggregate job `ci` must need every other job, run whatever their result and check each result
// (OQ-06 section 2.2). Text-based and dependency-free; scripts/workspace/workflows.ts checks the parsed YAML.
export function aggregateErrors(ci: string): string[] {
  const code = ci.split('\n').map((line) => line.replace(/(^|\s)#.*$/, '')).join('\n');
  const start = code.search(/^jobs:[ \t]*$/m);
  if (start < 0) return ['CI declares no jobs'];
  const rest = code.slice(start + 'jobs:'.length);
  const end = rest.search(/^\S/m);
  const body = end < 0 ? rest : rest.slice(0, end);
  const jobs = [...body.matchAll(/^  ([A-Za-z_][\w-]*):[ \t]*$/gm)];
  const aggregate = jobs.find((match) => match[1] === 'ci');
  if (!aggregate) return ['CI aggregate job ci is missing'];
  const next = jobs.find((match) => match.index > aggregate.index);
  const block = body.slice(aggregate.index, next?.index);
  const inline = /^    needs:[ \t]*\[([^\]]*)\][ \t]*$|^    needs:[ \t]*([\w-]+)[ \t]*$/m.exec(block);
  const listed = /^    needs:[ \t]*\n((?:      - [\w-]+[ \t]*\n)+)/m.exec(block);
  const needs = inline ? (inline[1] ?? inline[2]).split(',').map((item) => item.trim()).filter(Boolean) : listed ? [...listed[1].matchAll(/- ([\w-]+)/g)].map((match) => match[1]) : [];
  const errors: string[] = [];
  if (!/always\(\)/.test(block)) errors.push('CI aggregate must run with always()');
  for (const [, id] of jobs) if (id !== 'ci' && !needs.includes(id)) errors.push(`CI aggregate must need every other job: ${id}`);
  for (const id of needs) if (!new RegExp(`needs\\.${id.replace(/[-]/g, '\\-')}\\.result`).test(block)) errors.push(`CI aggregate must check the result of ${id}`);
  return errors;
}

export function checkRepository(base: string): string[] {
  const errors: string[] = [];
  let files: string[];
  try { files = paths(base); }
  catch (error) { return [String(error)]; }
  const all = new Set(files);
  for (const file of files) {
    const error = repositoryPathError(base,file,all);
    if (error) errors.push(error);
  }
  // Do not read any source through an invalid path, including required metadata.
  if (errors.length) return errors;
  errors.push(...developmentSkillErrors(base,all));
  errors.push(...agentAssetErrors(base,all));
  errors.push(...s0Errors(base,all));
  for (const file of ['README.md','AGENTS.md','LICENSE','SECURITY.md','CONTRIBUTING.md','CODE_OF_CONDUCT.md','TRADEMARKS.md','CHANGELOG.md','REPOSITORY_TREE.txt','docs/specs/README.md','.github/workflows/ci.yml']) {
    if (!all.has(file)) errors.push(`Missing required file: ${file}`);
  }
  const actualSpecs = files.filter((file) => /^docs\/specs\/\d{2}-.+\.md$/.test(file)).map((file) => file.split('/').at(-1));
  if (JSON.stringify(actualSpecs) !== JSON.stringify(expectedSpecs)) errors.push('Canonical spec set differs from the seven owners');
  try {
    if (read(base,'docs/specs/README.md') !== specIndex(base)) errors.push('Spec index drift: run pnpm generate:spec-index');
  } catch (error) { errors.push(`Spec metadata: ${error}`); }
  try {
    if (read(base,'REPOSITORY_TREE.txt') !== repositoryTree(files)) errors.push('Repository tree drift: stage intended files, then run pnpm generate:tree');
  } catch (error) { errors.push(`Repository tree: ${error}`); }
  for (const [prefix, count, file, pattern] of [
    ['A',18,'docs/specs/02-trading-domain-and-evaluation-spec.md',/^\| \*\*(A\d{2})\*\* \|/gm],
    ['R',10,'docs/specs/06-engineering-delivery-and-operations-spec.md',/^- \*\*(R\d{2}):\*\*/gm],
  ] as const) {
    try {
      const ids = [...read(base,file).matchAll(pattern)].map((match) => match[1]);
      const expected = Array.from({length:count}, (_,i) => `${prefix}${String(i+1).padStart(2,'0')}`);
      if (JSON.stringify(ids) !== JSON.stringify(expected)) errors.push(`${prefix} acceptance identifiers are missing, duplicated, or reordered`);
    } catch (error) { errors.push(`Acceptance: ${error}`); }
  }
  try {
    const archive = 'docs/research-logs/imported';
    const manifest = JSON.parse(read(base, `${archive}/manifest.json`));
    const declared = new Set<string>();
    if (manifest.canonical !== false) errors.push('Imported references must be non-canonical');
    for (const source of manifest.sources) {
      if (typeof source.file !== 'string' || source.file.includes('/') || source.file.includes('\\') || !source.file.endsWith('.md')) throw new Error('Invalid archive path');
      if (declared.has(source.file)) errors.push(`Duplicate archived source: ${source.file}`);
      declared.add(source.file);
      const path = `${archive}/${source.file}`;
      if (!all.has(path)) errors.push(`Missing tracked reference: ${path}`);
      const hash = createHash('sha256').update(readFileSync(resolve(base,path))).digest('hex');
      if (hash !== source.sha256) errors.push(`Source hash mismatch: ${source.file}`);
    }
    for (const file of files.filter((p)=>p.startsWith(`${archive}/`) && p.endsWith('.md') && !p.endsWith('/README.md'))) {
      if (!declared.has(file.slice(archive.length+1))) errors.push(`Unregistered source: ${file}`);
    }
  } catch (error) { errors.push(`Source archive: ${error}`); }
  for (const file of files) {
    const absolute = resolve(base,file);
    if (lstatSync(absolute).isSymbolicLink()) continue;
    if (/(^|\/)(\.env(?!\.example$)(\.|$)|\.dev\.vars(?!\.example$)(\.|$)|[^/]+\.tfstate(\.|$)|[^/]+\.pem$|[^/]+\.key$)/.test(file)) errors.push(`Private file must not be tracked: ${file}`);
    const text = read(base,file);
    // Vendored documentation can link to unselected files in its upstream repository.
    // Keep first-party Claude guidance and all non-link checks in scope.
    if (file.endsWith('.md') && !file.startsWith('docs/research-logs/imported/') && !file.startsWith('.agents/skills/')) errors.push(...localLinkErrors(base,file,text,all));
    errors.push(...credentialErrors(file,text));
    if (/^\.github\/workflows\/.*\.ya?ml$/.test(file)) {
      for (const match of text.matchAll(/^\s*-?\s*uses:\s*(\S+)/gm)) {
        if (!match[1].startsWith('./') && !/^[\w.-]+\/[\w./-]+@[0-9a-f]{40}$/.test(match[1])) errors.push(`Action must use a full commit SHA: ${file}: ${match[1]}`);
      }
      if (/pull_request_target\s*:/.test(text)) errors.push(`Privileged PR trigger is prohibited: ${file}`);
    }
  }
  try {
    const ci = read(base,'.github/workflows/ci.yml');
    if (!/^permissions:\n  contents: read$/m.test(ci)) errors.push('CI must declare read-only contents permission');
    if (/secrets\.|continue-on-error:\s*true|permissions:\s*write-all|contents:\s*write/.test(ci)) errors.push('CI must not use secrets, write permission, or ignored failures');
    errors.push(...aggregateErrors(ci));
  } catch (error) { errors.push(`CI: ${error}`); }
  return errors;
}
